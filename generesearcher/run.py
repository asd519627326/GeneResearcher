logger = logging.getLogger(__name__)


def _clear_analysis_exports(analysis_dir: Path) -> int:
    """Remove only generated exports from this function's analysis directory."""
    export_paths = [
        analysis_dir / filename
        for filename in (
            "step1_retrieved_papers_metadata.csv",
            "step3_relevance_filtered.csv",
            "step4_synthesis_results.csv",
            "step5_reporting_results.csv",
            # Generated by the earlier numbering before relevance filtering became Step 3.
            "step4_relevance_filtered.csv",
            "step5_synthesis_results.csv",
            "step6_reporting_results.csv",
            "analysis_report.md",
        )
    ]
    export_paths.extend(analysis_dir.glob("step2_embeddings_score*.csv"))

    removed = 0
    for path in export_paths:
        if path.is_file() or path.is_symlink():
            path.unlink()
            removed += 1

    references_dir = analysis_dir / "references"
    if references_dir.is_dir():
        for path in references_dir.glob("*.txt"):
            if path.is_file() or path.is_symlink():
                path.unlink()
                removed += 1
        try:
            references_dir.rmdir()
        except OSError:
            # Preserve the directory if it contains user-managed non-TXT files.
            pass

    return removed


def _has_article_level_summaries(synthesis_df: Any) -> bool:
    """Return whether Step 4 persisted at least one non-empty per-document summary."""
    required_columns = {"Summary_Level", "Summary_Text"}
    if synthesis_df.empty or not required_columns.issubset(synthesis_df.columns):
        return False

    is_document_summary = (
        synthesis_df["Summary_Level"]
        .fillna("")
        .astype(str)
        .str.casefold()
        .eq("per_document")
    )
    has_summary_text = (
        synthesis_df["Summary_Text"]
        .fillna("")
        .astype(str)
        .str.strip()
        .ne("")
    )
    return bool((is_document_summary & has_summary_text).any())


class _PipelineExecutor:
    """
    Internal executor for the six analysis stages.
    """

    def __init__(
        self,
        project_folder: str = "GeneResearch",
        env_file: Optional[str | Path] = None,
        spacy_nlp: Optional[Any] = None,
    ):
        """
        初始化 Pipeline。
        :param project_folder: 研究背景对应的项目根目录。
        :param env_file: 可选的环境变量文件路径。
        """
        self.services = initialize_services(env_file=env_file)
        if spacy_nlp is not None:
            self.services["spacy_nlp"] = spacy_nlp
        self.project_folder = str(project_folder)

    def get_analysis_directory(self, analysis_data: AnalysisData) -> Path:
        """Return the directory for one function within a research project."""
        safe_function_name = analysis_directory_name(analysis_data.function_name)
        project_folder = analysis_data.project_folder or self.project_folder
        return Path(project_folder) / f"analysis_{safe_function_name}"

    def _reload_authoritative_state(self, analysis_data: AnalysisData) -> AnalysisData:
        """Reload stage inputs from Milvus, the canonical analysis store."""
        loaded = restore_analysis_state(self.get_analysis_directory(analysis_data))
        if loaded is None:
            raise RuntimeError("Could not restore the analysis state from the database.")
        return loaded

    def prepare_fresh_analysis(self, analysis_data: AnalysisData) -> Path:
        """Prepare a clean database and export directory for a new session."""
        if not analysis_data.project_folder:
            analysis_data.project_folder = self.project_folder

        logger.info(
            "Preparing analysis for target function '%s' and target gene(s) %s in '%s'.",
            analysis_data.function_name,
            ", ".join(analysis_data.genes),
            analysis_data.project_folder,
        )
        analysis_dir = _setup_project_structure(
            analysis_data.project_folder,
            analysis_data.function_name,
            analysis_data.to_persisted_parameters(self.services),
        )
        db_path = analysis_dir / "step2_embeddings.db"
        if db_path.exists():
            warnings.warn(
                f"Existing analysis data will be cleared before this new session: {db_path}",
                UserWarning,
                stacklevel=2,
            )
            logger.warning(
                "Existing analysis database '%s' will be cleared before retrieval starts.",
                db_path,
            )
            database_manager = MilvusManager(
                db_path=str(db_path),
                collection_name="biomed_sentences",
                dimension=self.services["embedding_manager"].dimensions,
            )
            try:
                database_manager.clear_all_collections()
            finally:
                database_manager.close()

        removed_exports = _clear_analysis_exports(analysis_dir)
        if removed_exports:
            logger.info("Removed %s old export file(s) before the new run.", removed_exports)
        else:
            logger.debug("No old export files needed clearing.")
        return analysis_dir

    @log_operation("Step 1/6 literature retrieval")
    async def run_step_1_retrieval(
        self,
        analysis_data: AnalysisData,
        prepared_analysis_directory: Optional[Path] = None,
    ) -> AnalysisData:
        """
        步骤 1：文献检索
        """
        # 如果 config 中没有指定 project_folder，则注入 Pipeline 的默认 project_folder
        if not analysis_data.project_folder:
            analysis_data.project_folder = str(self.project_folder)
            logger.debug("Using pipeline project folder '%s' from the pipeline configuration.", self.project_folder)
        
        # 执行检索 (run_retrieval_step 内部会自动保存到磁盘)
        result_data = await run_retrieval_step(
            self.services,
            analysis_data,
            prepared_analysis_dir=prepared_analysis_directory,
        )
        if result_data.raw_papers_df.empty:
            return result_data
        return self._reload_authoritative_state(result_data)

    @log_operation("Step 2/6 sentence-level semantic retrieval")
    async def run_step_2_semantic_filter(
        self,
        analysis_data: AnalysisData,
        minimum_cosine_similarity: float = 0.5609,
    ) -> AnalysisData:
        """
        步骤 2：向量化与召回
        :param analysis_data: 上一步(Step 1)返回的 AnalysisData 对象
        """
        if analysis_data.retrieval_status == "no_results":
            raise ValueError(
                "Step 1 completed with zero retrieved papers; Step 2 will not reload older database rows."
            )

        analysis_data = self._reload_authoritative_state(analysis_data)
        if analysis_data.raw_papers_df.empty:
            raise ValueError("Missing Step 1 data in the database. Cannot proceed to Step 2.")

        # 2. 入库 (Ingestion)
        await run_ingestion_pipeline(
            analysis_data,
            self.services,
            show_progress=progress_enabled(logger),
        )

        # 3. 召回 (Recall)
        await run_recall_pipeline(
            analysis_data, 
            self.services, 
            minimum_cosine_similarity=minimum_cosine_similarity,
            top_k=16384
        )
        
        # The recall rows (including original sentence text) were committed to
        # Milvus; reload them so the next step receives only canonical values.
        return self._reload_authoritative_state(analysis_data)

    @log_operation("Step 3/6 Assessment of Candidate Evidence")
    async def run_step_3_relevance_filter(
        self,
        analysis_data: AnalysisData,
        minimum_cosine_similarity: float = 0.5,
        batch_run_id: Optional[str] = None,
    ) -> AnalysisData:
        """
        步骤 3：LLM 相关性过滤
        :param analysis_data: 上一步(Step 2)返回的 AnalysisData 对象
        """
        analysis_data = self._reload_authoritative_state(analysis_data)
        if analysis_data.recalled_sentences_df.empty:
             raise ValueError("Missing Step 2 data. Cannot proceed to Step 3.")

        # 2. 执行过滤
        result_data = await run_relevance_filter_step(
            analysis_data,
            self.services,
            minimum_cosine_similarity=minimum_cosine_similarity,
            batch_run_id=batch_run_id,
        )
        return result_data

    @log_operation("Step 4/6 LLM-Guided evidence synthesis")
    async def run_step_4_synthesis(
        self,
        analysis_data: AnalysisData,
        batch_run_id: Optional[str] = None,
    ) -> AnalysisData:
        """步骤 4：综合"""
        analysis_data = self._reload_authoritative_state(analysis_data)
        if analysis_data.relevance_filter_status in {"failed", "partial", "no_candidates", "stale"}:
            raise ValueError(
                "Step 3 did not produce usable current results "
                f"(status={analysis_data.relevance_filter_status}); Step 4 will not reuse older rows."
            )

        result_data = await run_synthesis_step(analysis_data, self.services, batch_run_id=batch_run_id)
        return result_data

    @log_operation("Step 5/6 individual gene function interpretation and multi-gene analysis")
    async def run_step_5_reporting(self, analysis_data: AnalysisData) -> AnalysisData:
        """步骤 5：报告"""
        analysis_data = self._reload_authoritative_state(analysis_data)
        if not _has_article_level_summaries(analysis_data.synthesis_df):
            raise ValueError(
                "Step 4 did not produce any article-level literature summaries. "
                "Cannot proceed to Step 5."
            )

        result_data = await run_reporting_step(analysis_data, self.services)
        return result_data

    @log_operation("Step 6/6 Markdown report generation")
    async def run_step_6_report_generation(self, analysis_data: AnalysisData) -> AnalysisData:
        """步骤 6：从数据库中的报告状态生成 Markdown 文件。"""
        analysis_data = self._reload_authoritative_state(analysis_data)
        if not _has_article_level_summaries(analysis_data.synthesis_df):
            raise ValueError(
                "Step 4 did not produce any article-level literature summaries. "
                "Cannot generate the Markdown report."
            )
        result_data = render_markdown_report(analysis_data, self.services)
        return result_data

